"""Prepare readable, non-secret container network files without changing host DNS."""
from __future__ import annotations

import argparse
import ipaddress
import os
import re
import stat
import tempfile
from pathlib import Path

HEADER = "# Generated by review-bot prepare-network\n"


def prepare_network(directory: Path, model_address: str, *, model_host: str,
                    resolver: Path = Path("/etc/resolv.conf")) -> None:
    address = ipaddress.ip_address(model_address)
    if (not isinstance(model_host, str) or not model_host.isascii() or len(model_host) > 253
        or any(not re.fullmatch(r"[A-Za-z0-9](?:[A-Za-z0-9-]{0,61}[A-Za-z0-9])?", label)
               for label in model_host.split("."))
        or model_host.lower() in ("localhost", "ip6-localhost")):
        raise ValueError("Use one explicit model hostname")
    if not directory.is_absolute() or directory.is_symlink():
        raise ValueError("Use an absolute owned network configuration directory")
    directory.mkdir(mode=0o700, parents=True, exist_ok=True)
    metadata = directory.stat()
    if metadata.st_uid != os.geteuid() or stat.S_IMODE(metadata.st_mode) != 0o700:
        raise ValueError("Network configuration directory must be owned and mode 0700")
    values = {"hosts": HEADER + f"127.0.0.1 localhost\n::1 localhost ip6-localhost\n{address} {model_host.lower()}\n",
        "resolv.conf": HEADER + resolver.read_text(encoding="utf-8")}
    for name in values:
        path = directory / name
        if path.exists() or path.is_symlink():
            info = path.lstat()
            if not stat.S_ISREG(info.st_mode) or info.st_uid != os.geteuid() or info.st_nlink != 1 or not path.read_text().startswith(HEADER):
                raise ValueError("Refusing to replace an unrelated network configuration file")
    for name, value in values.items():
        fd, pending = tempfile.mkstemp(prefix=".pending-", dir=directory)
        try:
            with os.fdopen(fd, "w", encoding="utf-8") as stream:
                os.fchmod(stream.fileno(), 0o644)
                stream.write(value)
                stream.flush()
                os.fsync(stream.fileno())
            os.replace(pending, directory / name)
        finally:
            if os.path.exists(pending):
                os.unlink(pending)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--directory", required=True, type=Path)
    parser.add_argument("--model-address", required=True)
    parser.add_argument("--model-host", required=True)
    args = parser.parse_args()
    prepare_network(args.directory, args.model_address, model_host=args.model_host)
